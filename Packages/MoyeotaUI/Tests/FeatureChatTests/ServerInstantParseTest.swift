import Foundation
import Testing
@testable import FeatureChat

/// 서버 `Instant` 파싱(`String.toInstantOrNull`) — 원본 `Instant.parse` → `OffsetDateTime.parse` 두 단계와
/// **같은 입력을 받는가**(`docs/PORTING.md` 6장).
///
/// 원본에 없는 테스트다. 원본은 JDK 파서라 소수 초 유무를 저절로 받지만, iOS `ISO8601DateFormatter` 는
/// 옵션 하나로 소수 초를 「있어야 함」 또는 「없어야 함」으로 갈라 한쪽을 버린다. 서버가 소수 초를 어떤 때는
/// 싣고 어떤 때는 안 실으면 시각 칸이 조용히 비고 목록 정렬이 방 id 로 떨어진다.
///
/// 기대값은 JDK 25(Temurin 25.0.2)에서 원본과 같은 두 단계를 실제로 돌려 받은 결과다. `nil` 은 파싱 실패다.
@Suite struct ServerInstantParseTest {

    private static let accepted: [(input: String, millis: Int64)] = [
        // 소수 초 — 없음, 1~9자리, 점만
        ("2026-09-07T08:36:12Z", 1_788_770_172_000),
        ("2026-09-07T08:36:12.1Z", 1_788_770_172_100),
        ("2026-09-07T08:36:12.12Z", 1_788_770_172_120),
        ("2026-09-07T08:36:12.123Z", 1_788_770_172_123),
        ("2026-09-07T08:36:12.123456Z", 1_788_770_172_123),
        ("2026-09-07T08:36:12.123456789Z", 1_788_770_172_123),
        ("2026-09-07T08:36:12.Z", 1_788_770_172_000),
        // 오프셋
        ("2026-09-07T08:36:12+09:00", 1_788_737_772_000),
        ("2026-09-07T08:36:12.5+09:00", 1_788_737_772_500),
        ("2026-09-07T08:36:12-03:30", 1_788_782_772_000),
        ("2026-09-07T08:36:12+09", 1_788_737_772_000),
        ("2026-09-07T08:36:12+09:00:30", 1_788_737_742_000),
        ("2026-09-07T08:36:12+18:00", 1_788_705_372_000),
        ("2026-09-07T08:36:12-18:00", 1_788_834_972_000),
        // 초 생략
        ("2026-09-07T08:36+09:00", 1_788_737_760_000),
        ("2026-09-07T08:36Z", 1_788_770_160_000),
        // 소문자
        ("2026-09-07t08:36:12z", 1_788_770_172_000),
        ("2026-09-07t08:36:12+09:00", 1_788_737_772_000),
        // 하루의 끝과 윤초
        ("2026-09-07T24:00:00Z", 1_788_825_600_000),
        ("2026-09-07T24:00:00+09:00", 1_788_793_200_000),
        ("2026-09-07T24:00:00.000Z", 1_788_825_600_000),
        ("2026-09-07T23:59:60Z", 1_788_825_599_000),
        ("2026-09-07T23:59:60.5Z", 1_788_825_599_500),
        ("2026-09-07T23:59:60+09:00", 1_788_793_199_000),
        // 달력 경계
        ("2028-02-29T00:00:00Z", 1_835_395_200_000),
        // 연도 표기
        ("+12026-09-07T08:36:12Z", 317_358_290_172_000),
        ("-0001-01-01T00:00:00Z", -62_198_755_200_000),
        ("0000-01-01T00:00:00Z", -62_167_219_200_000),
        // 1970 이전의 밀리초 내림 — 초를 Double 로 들고 있으면 어긋나는 자리
        ("1969-12-31T23:59:59.999Z", -1),
        ("1969-12-31T23:59:59.9999Z", -1),
        ("1970-01-01T00:00:00Z", 0),
    ]

    private static let rejected: [String] = [
        "2026-09-07T08:36:12.1234567891Z", // 소수 10자리
        "2026-09-07T08:36:12+0900", // 콜론 없는 오프셋
        "2026-09-07T08:36:12+090030",
        "2026-09-07T08:36:12+9",
        "2026-09-07T08:36:12+18:01", // ±18:00 초과
        "2026-09-07T08:36:12+19:00",
        "2026-09-07T08:36:12+09:60",
        "2026-09-07T24:00Z", // 24시는 초까지 있어야 한다
        "2026-09-07T24:00:01Z",
        "2026-09-07T22:59:60Z", // 윤초는 23:59 에만
        "2026-02-29T00:00:00Z", // 평년 2월 29일
        "2026-13-01T00:00:00Z",
        "2026-09-31T00:00:00Z",
        "2026-09-07T25:00:00Z",
        "2026-09-07T08:60:00Z",
        "2026-09-07T08:36:61Z",
        "2026-9-7T08:36:12Z",
        "2026-09-07 08:36:12Z",
        "2026-09-07T08:36:12", // 시간대 없음 — toTimeLabel 만 잘라 쓴다
        "2026-09-07T08:36:12.123",
        "2026-09-07",
        "2026-09-07T08:36:12Z ",
        " 2026-09-07T08:36:12Z",
        "+2026-09-07T08:36:12Z", // `+` 는 다섯 자리 이상
        "12026-09-07T08:36:12Z", // 다섯 자리는 `+` 가 있어야 한다
        "-001-01-01T00:00:00Z",
        "2026-09-07T08:36:12\u{FF3A}", // 전각 Z
        "\u{0662}\u{0660}\u{0662}\u{0666}-09-07T08:36:12Z", // 아라비아 숫자
        "어제",
        "",
    ]

    @Test("원본이 받는 꼴은 같은 밀리초로 읽는다")
    func acceptsSameInputs() {
        for (input, millis) in Self.accepted {
            #expect(input.toEpochMillisOrNull() == millis, "\(input)")
        }
    }

    @Test("원본이 거절하는 꼴은 거절한다")
    func rejectsSameInputs() {
        for input in Self.rejected {
            #expect(input.toEpochMillisOrNull() == nil, "\(input)")
        }
    }

    /// `PORTING.md` 6장이 지목한 그 경우 — 서버 응답이 어느 쪽이어도 말풍선 시각이 같아야 한다.
    @Test("소수 초 유무와 상관없이 같은 시각을 그린다")
    func labelDoesNotDependOnFraction() {
        let seoul = TimeZone(identifier: "Asia/Seoul")!
        #expect("2026-09-07T08:36:12Z".toTimeLabel(zone: seoul) == "17:36")
        #expect("2026-09-07T08:36:12.123456Z".toTimeLabel(zone: seoul) == "17:36")
    }
}
